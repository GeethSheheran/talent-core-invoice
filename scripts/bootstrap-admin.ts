import { createClient } from "@supabase/supabase-js";
import { z } from "zod";
const email = z.email().parse(process.env.BOOTSTRAP_ADMIN_EMAIL);
const url = z.url().parse(process.env.NEXT_PUBLIC_SUPABASE_URL);
const key = z.string().min(10).parse(process.env.SUPABASE_SECRET_KEY);
const db = createClient(url, key, {
  auth: { autoRefreshToken: false, persistSession: false },
});
let id: string | undefined;
for (let page = 1; page < 1000; page++) {
  const { data, error } = await db.auth.admin.listUsers({ page, perPage: 100 });
  if (error) throw new Error("Could not inspect Auth users");
  id = data.users.find(
    (u) => u.email?.toLowerCase() === email.toLowerCase(),
  )?.id;
  if (id || data.users.length < 100) break;
}
if (!id)
  throw new Error(
    "Create this administrator in Supabase Auth first. Then rerun bootstrap. No password or invitation is generated by this script.",
  );
const { error } = await db
  .from("admin_members")
  .upsert({ user_id: id, active: true });
if (error)
  throw new Error(
    "Membership update failed. Apply the migrations and verify the server key.",
  );
console.log(
  "Administrator membership activated for the explicitly configured Auth user.",
);
