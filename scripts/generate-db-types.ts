// Generate from a fresh PostgreSQL-compatible instance running the actual migrations.
import { database } from "../tests/fixtures/database";
import { writeFile } from "node:fs/promises";
const db = await database();
await db.exec("reset role");
const columns = await db.query<{
  table_name: string;
  column_name: string;
  data_type: string;
  udt_name: string;
  is_nullable: string;
  column_default: string | null;
}>(
  `select table_name,column_name,data_type,udt_name,is_nullable,column_default from information_schema.columns where table_schema='public' order by table_name,ordinal_position`,
);
const views = await db.query<{ table_name: string }>(
  `select table_name from information_schema.views where table_schema='public'`,
);
const viewNames = new Set(views.rows.map((v) => v.table_name));
function type(name: string) {
  if (["int2", "int4", "int8", "numeric", "integer", "bigint"].includes(name))
    return "number";
  if (name === "bool" || name === "boolean") return "boolean";
  if (name === "jsonb" || name === "json") return "Json";
  if (name === "_int4" || name === "integer[]") return "number[]";
  return "string";
}
let out =
  "// Generated by npm run db:types from actual migrations. Do not edit.\nexport type Json = string | number | boolean | null | {[key:string]:Json|undefined} | Json[];\nexport type Database = { public: { Tables: {\n";
for (const view of [false, true]) {
  if (view) out += "}; Views: {\n";
  for (const table of new Set(columns.rows.map((c) => c.table_name))) {
    if (viewNames.has(table) !== view) continue;
    const fields = columns.rows.filter((c) => c.table_name === table);
    out += `${table}: { Row: {\n`;
    for (const c of fields)
      out += `${c.column_name}: ${type(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};\n`;
    out += "};";
    if (!view) {
      for (const mode of ["Insert", "Update"]) {
        out += `${mode}: {\n`;
        for (const c of fields)
          out += `${c.column_name}${mode === "Update" || c.is_nullable === "YES" || c.column_default ? "?" : ""}: ${type(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};\n`;
        out += "};";
      }
    }
    out += "Relationships: []; };\n";
  }
}
out += "}; Functions: {\n";
const funcs = await db.query<{ proname: string; args: string; result: string }>(
  `select p.proname,pg_get_function_arguments(p.oid) args,pg_get_function_result(p.oid) result from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' order by p.proname`,
);
for (const f of funcs.rows) {
  out += `${f.proname}: { Args: {`;
  for (const a of f.args.split(",").filter(Boolean)) {
    const parts = a.trim().split(" ");
    out += `${parts[0]}: ${type(parts.slice(1).join(" "))}${(parts[0] === "p_id" && f.proname === "save_record") || parts[0] === "p_repeat" || parts[0] === "p_provider" ? " | null" : ""};`;
  }
  out += `}; Returns: ${f.result === "void" ? "undefined" : f.result === "SETOF outbox_jobs" ? "Database['public']['Tables']['outbox_jobs']['Row'][]" : type(f.result)}; };\n`;
}
out +=
  '}; Enums: Record<string, never>; CompositeTypes: Record<string, never>; }; };\nexport type Tables<K extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][K]["Row"];\n';
await writeFile("src/lib/db/database.types.ts", out);
await db.close();
console.log("Generated database types from applied migrations.");
