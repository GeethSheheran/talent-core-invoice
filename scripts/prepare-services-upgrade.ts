import { readFile, writeFile } from "node:fs/promises";

// Existing migrations are atomic. Check their schema markers so SQL Editor
// installations (which have no CLI migration history) can also be upgraded.
const steps = [
  [
    "20261022112205_expenses_and_recurring_schedules.sql",
    "to_regclass('public.company_expenses') is null",
  ],
  [
    "20261027093351_attach_pending_expenses.sql",
    "to_regprocedure('public.attach_pending_expenses(uuid,jsonb)') is null",
  ],
  [
    "20261029120543_service_catalogue_delete.sql",
    "to_regprocedure('public.delete_service(uuid)') is null",
  ],
  [
    "20261029122337_payment_cheque_method.sql",
    "not exists (select 1 from pg_constraint where conrelid='public.payments'::regclass and conname='payments_method_check' and pg_get_constraintdef(oid) like '%cheque%')",
  ],
  [
    "20261029130000_services_hierarchy_packages_and_credit_rollover.sql",
    "not exists (select 1 from information_schema.columns where table_schema='public' and table_name='agreements' and column_name='managed_services')",
  ],
  [
    "20261029130001_agreed_service_discount_options.sql",
    "not exists (select 1 from information_schema.columns where table_schema='public' and table_name='projects' and column_name='discount_type')",
  ],
  [
    "20261105094507_workbook_catalogue_import.sql",
    "to_regprocedure('public.import_service_catalogue(jsonb)') is null",
  ],
  ["20261106061929_allow_main_service_deletion.sql", "true"],
];
let sql = `-- Complete upgrade for existing Ledger installations; run the ENTIRE file as postgres.
-- Generated by: npx tsx scripts/prepare-services-upgrade.ts
-- Back up first. Requires the three core migrations. Does not create sample data.
-- Supports intact migrations only: a manually partially applied migration needs inspection.
-- Schema markers skip installed migrations; no existing balances are recalculated.
begin;
select pg_advisory_xact_lock(20261105);
do $preflight$ begin
  if to_regclass('public.service_catalogue') is null
     or to_regprocedure('private.assert_admin()') is null then
    raise exception 'Core Ledger schema is missing. This is an upgrade, not initial setup.';
  end if;
end $preflight$;
`;
for (const [file, condition] of steps) {
  const source = await readFile(`supabase/migrations/${file}`, "utf8");
  sql += `\n-- ${file}\ndo $upgrade$ begin\nif ${condition} then\nexecute $migration$\n${source}\n$migration$;\nend if;\nend $upgrade$;\n`;
}
sql += `
-- Verify without returning customer data.
select parent_id, billing_type from public.service_catalogue limit 0;
select items, discount_type, discount_value from public.projects limit 0;
select to_regprocedure('public.save_record(text,uuid,jsonb)') as save_service_rpc;
notify pgrst, 'reload schema';
commit;
`;
await writeFile("supabase/services-upgrade.sql", sql);
console.log("Prepared supabase/services-upgrade.sql");
